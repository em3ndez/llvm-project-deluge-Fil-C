static void clmul64(uint64_t a, uint64_t b, uint64_t out[2])
{
    out[0] = 0;
    out[1] = 0;
    int i;
    for (i = 0; i < 64; i++) {
        if ((b >> i) & 1) {
            out[0] ^= a << i;
            if (i)
                out[1] ^= a >> (64 - i);
        }
    }
}

